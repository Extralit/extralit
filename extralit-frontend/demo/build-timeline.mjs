/**
 * Bridges the Playwright recording into the Remotion project:
 *   1. transcodes the raw headless-chromium .webm into a constant-frame-rate h264 mp4
 *      (Remotion's <Video> needs a seekable, CFR source — the webm is VFR),
 *   2. generates `video/src/data.ts` from `timeline.json` so the composition's scene
 *      boundaries, captions and assertion rail come from the run that actually happened.
 *
 * `data.ts` is generated, not committed: the composition is a *report* on a specific run,
 * so it must never be able to render stale captions against a fresh recording.
 *
 * Usage: node build-timeline.mjs --out <recording dir> [--commit <sha>]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : process.argv[i + 1];
};

const OUT = arg("out");
if (!OUT) throw new Error("--out <recording dir> is required");

const commit =
  arg("commit") ?? execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: HERE }).toString().trim();

const videoDir = join(OUT, "video");
const webm = readdirSync(videoDir).find((f) => f.endsWith(".webm"));
if (!webm) throw new Error(`no .webm recording found in ${videoDir}`);

const publicDir = join(HERE, "video", "public");
mkdirSync(publicDir, { recursive: true });
const mp4 = join(publicDir, "screen.mp4");

execFileSync(
  "ffmpeg",
  // -r 30 forces CFR; -an drops the (silent) audio track.
  ["-y", "-i", join(videoDir, webm), "-c:v", "libx264", "-preset", "veryfast", "-crf", "20",
   "-pix_fmt", "yuv420p", "-r", "30", "-an", mp4],
  { stdio: ["ignore", "ignore", "inherit"] }
);

// The transcode's duration is authoritative, not the wall-clock the driver measured: the
// composition's frame count is derived from it, and a mismatch would drift the captions.
const videoDurationSec = Number(
  execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration",
                           "-of", "default=nw=1:nk=1", mp4]).toString().trim()
);

const timeline = JSON.parse(readFileSync(join(OUT, "timeline.json"), "utf-8"));

const data = {
  commit,
  videoDurationSec,
  width: timeline.width,
  height: timeline.height,
  totalChecks: timeline.totalChecks,
  failures: timeline.failures,
  pageErrors: timeline.pageErrors,
  consoleErrors: timeline.consoleErrors,
  scenes: timeline.scenes.map((s) => ({
    id: s.id,
    title: s.title,
    caption: s.caption,
    startMs: s.startMs,
    endMs: s.endMs,
    ok: s.ok,
    checks: s.checks.map((c) => ({ label: c.label, ok: c.ok })),
  })),
};

writeFileSync(
  join(HERE, "video", "src", "data.ts"),
  `// GENERATED by build-timeline.mjs from a Playwright run's timeline.json — do not edit.\n` +
    `export const demo = ${JSON.stringify(data, null, 2)} as const;\n`
);

console.log(
  `screen.mp4 ${videoDurationSec.toFixed(2)}s · ${data.scenes.length} scenes · ` +
    `${data.totalChecks} checks · ${data.failures.length} failed · ${data.pageErrors.length} page errors`
);
